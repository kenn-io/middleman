func TestLaunchWorkspaceRuntimeSessionPreparesAgentContext(t *testing.T) {
	runParallelServerTest(t)
	acquireRootWorkspaceGitSlot(t)
	assert := assert.New(t)
	require := require.New(t)
	d := dbtest.Open(t)
	worktree := initServerWorkspaceGitRepo(t)
	repoID := seedServerWorkspaceRepo(t, d)
	seedServerWorkspaceMR(t, d, repoID)

	ws := &db.Workspace{
		ID:              "ws-agent-context",
		Platform:        "github",
		PlatformHost:    "github.com",
		RepoOwner:       "acme",
		RepoName:        "widget",
		ItemType:        db.WorkspaceItemTypePullRequest,
		ItemNumber:      42,
		GitHeadRef:      "feature/widgets",
		WorkspaceBranch: "feature/widgets",
		WorktreePath:    worktree,
		TmuxSession:     "kenn-forge-ws-agent-context",
		TerminalBackend: "tmux",
		Status:          "ready",
	}
	require.NoError(d.InsertWorkspace(t.Context(), ws))
	seedServerWorkspaceLaunchSpec(t, d, ws, repoID)
	require.NoError(os.WriteFile(
		filepath.Join(worktree, "AGENTS.md"),
		[]byte("# Repository Agent Rules\n\nKeep this guidance.\n"), 0o644,
	))
	runServerWorkspaceTestGit(t, worktree, "add", "AGENTS.md")
	runServerWorkspaceTestGit(t, worktree, "commit", "-m", "add agent rules")
	staleMarked := "<!-- generated by kenn-forge; safe to delete; regenerated on agent launch -->\nstale\n"
	require.NoError(os.WriteFile(filepath.Join(worktree, "AGENTS.override.md"), []byte(staleMarked), 0o644))

	tmuxPath := writeRuntimeTmuxLifecycleRecorder(t, t.TempDir(), filepath.Join(t.TempDir(), "tmux-record"))
	runtime := localruntime.NewManager(localruntime.Options{
		Targets: []localruntime.LaunchTarget{
			{
				Key:       "Codex yolo",
				Label:     "Codex",
				Kind:      localruntime.LaunchTargetAgent,
				Command:   []string{"/bin/sh", "-c", "exit 0"},
				Available: true,
			},
			{
				Key:       string(localruntime.LaunchTargetShell),
				Label:     "tmux",
				Kind:      localruntime.LaunchTargetShell,
				Command:   []string{tmuxPath},
				Available: true,
			},
		},
		TmuxCommand:             []string{tmuxPath},
		WrapAgentSessionsInTmux: true,
	})
	handler := workspaceapi.New(workspaceapi.Deps{
		DB:         d,
		Workspaces: workspace.NewManager(d, t.TempDir()),
		Runtime:    runtime,
	})
	input := &workspaceapi.LaunchWorkspaceRuntimeSessionInput{ID: ws.ID}
	input.Body.TargetKey = "Codex yolo"

	_, err := handler.LaunchWorkspaceRuntimeSession(t.Context(), input)
	require.NoError(err)

	override, err := os.ReadFile(filepath.Join(worktree, "AGENTS.override.md"))
	require.NoError(err)
	content := string(override)
	assert.Contains(content, "Source kind: pull request")
	assert.Contains(content, "PR: #42")
	assert.Contains(content, "Push branch: feature/widgets")
	assert.NotContains(content, "stale")
	assert.Less(
		strings.Index(content, "# Kenn Forge Workspace Context"),
		strings.Index(content, "# Repository Agent Rules"),
	)
	assert.True(strings.HasSuffix(content, "# Repository Agent Rules\n\nKeep this guidance.\n"))
	assert.NoFileExists(filepath.Join(worktree, "CLAUDE.local.md"))
	assertServerGitIgnored(t, worktree, "AGENTS.override.md")
	status := strings.TrimSpace(string(runServerWorkspaceTestGit(t, worktree, "status", "--porcelain")))
	assert.Empty(status)
}

func TestWorkspaceRuntimeLaunchWritesAgentContextE2E(t *testing.T) {
	runParallelServerTest(t)
	acquireRootWorkspaceGitSlot(t)

	assert := assert.New(t)
	require := require.New(t)
	dir := t.TempDir()
	tmuxPath := writeRuntimeTmuxLifecycleRecorder(t, dir, filepath.Join(dir, "tmux-record"))
	agentPath := filepath.Join(dir, "helper-agent")
	require.NoError(os.WriteFile(agentPath, []byte("#!/bin/sh\nexit 0\n"), 0o755))
	cfg := &config.Config{
		Agents: []config.Agent{{Key: "codex", Label: "Codex", Command: []string{agentPath}}},
		Tmux:   config.Tmux{Command: []string{tmuxPath}},
	}
	client, _, _, _, _ := setupTestServerWithWorkspacesServer(t, cfg)
	ctx := context.Background()
	ws := createReadyWorkspace(t, ctx, client)

	assert.NoFileExists(filepath.Join(ws.WorktreePath, "AGENTS.override.md"))

	resp, err := client.HTTP.LaunchWorkspaceRuntimeSessionWithResponse(
		ctx, ws.Id,
		generated.LaunchWorkspaceRuntimeSessionInputBody{TargetKey: "codex"},
	)
	require.NoError(err)
	require.Equal(http.StatusOK, resp.StatusCode())

	agentsLocal, err := os.ReadFile(filepath.Join(ws.WorktreePath, "AGENTS.override.md"))
	require.NoError(err)
	assert.Contains(string(agentsLocal), "Source kind: pull request")
	assert.Contains(string(agentsLocal), "Push branch:")
	assert.NotContains(string(agentsLocal), "Working branch")
	assert.NoFileExists(filepath.Join(ws.WorktreePath, "CLAUDE.local.md"))
	assertServerGitIgnored(t, ws.WorktreePath, "AGENTS.override.md")
	status := strings.TrimSpace(string(runServerWorkspaceTestGit(
		t, ws.WorktreePath, "status", "--porcelain",
	)))
	assert.Empty(status)
}

func TestWorkspaceRuntimeLaunchRejectsUnsafeRepositoryAgentInstructionsE2E(t *testing.T) {
	runParallelServerTest(t)
	acquireRootWorkspaceGitSlot(t)

	tests := []struct {
		name      string
		entry     string
		forbidden string
	}{
		{name: "symlink", entry: "symlink", forbidden: "host secret"},
		{name: "oversized file", entry: "oversized", forbidden: strings.Repeat("x", 128)},
	}
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			assert := assert.New(t)
			require := require.New(t)
			dir := t.TempDir()
			tmuxPath := writeRuntimeTmuxLifecycleRecorder(t, dir, filepath.Join(dir, "tmux-record"))
			agentPath := filepath.Join(dir, "helper-agent")
			require.NoError(os.WriteFile(agentPath, []byte("#!/bin/sh\nexit 0\n"), 0o755))
			cfg := &config.Config{
				Agents: []config.Agent{{Key: "codex", Label: "Codex", Command: []string{agentPath}}},
				Tmux:   config.Tmux{Command: []string{tmuxPath}},
			}
			client, _, _, _, _ := setupTestServerWithWorkspacesServer(t, cfg)
			ctx := context.Background()
			ws := createReadyWorkspace(t, ctx, client)
			agentsPath := filepath.Join(ws.WorktreePath, "AGENTS.md")
			switch tt.entry {
			case "symlink":
				target := filepath.Join(t.TempDir(), "AGENTS.md")
				require.NoError(os.WriteFile(target, []byte(tt.forbidden), 0o644))
				require.NoError(os.Symlink(target, agentsPath))
			case "oversized":
				require.NoError(os.WriteFile(agentsPath, []byte(strings.Repeat("x", (1<<20)+1)), 0o644))
			}

			resp, err := client.HTTP.LaunchWorkspaceRuntimeSessionWithResponse(
				ctx, ws.Id,
				generated.LaunchWorkspaceRuntimeSessionInputBody{TargetKey: "codex"},
			)
			require.NoError(err)
			require.Equal(http.StatusOK, resp.StatusCode())

			override, err := os.ReadFile(filepath.Join(ws.WorktreePath, "AGENTS.override.md"))
			require.NoError(err)
			content := string(override)
			assert.Contains(content, "Source kind: pull request")
			assert.NotContains(content, tt.forbidden)
		})
	}
}

func TestWorkspaceRuntimeLaunchWritesIssueAndKataAgentContextE2E(t *testing.T) {
	runParallelServerTest(t)
	acquireRootWorkspaceGitSlot(t)

	assert := assert.New(t)
	require := require.New(t)
	dir := t.TempDir()
	database := dbtest.Open(t)
	syncer := ghclient.NewSyncer(nil, database, nil, nil, time.Minute, nil, nil)
	t.Cleanup(syncer.Stop)
	tmuxPath := writeRuntimeTmuxLifecycleRecorder(t, dir, filepath.Join(dir, "tmux-record"))
	cfg := &config.Config{
		Tmux: config.Tmux{Command: []string{tmuxPath}},
		Agents: []config.Agent{{
			Key:     "codex",
			Label:   "Codex",
			Command: []string{"/bin/sh", "-c", "exit 0"},
		}},
	}
	srv := New(
		database, syncer, nil, "/", cfg,
		ServerOptions{
			WorktreeDir:                        filepath.Join(dir, "worktrees"),
			DisableWorkspaceBackgroundMonitors: true,
		},
	)
	t.Cleanup(func() { gracefulShutdown(t, srv) })

	issueWorktree := initServerWorkspaceGitRepo(t)
	seedIssue(t, database, "acme", "widget", 7, "open")
	issueWorkspace := &db.Workspace{
		ID: "ws-issue-context", Platform: "github", PlatformHost: "github.com",
		RepoOwner: "acme", RepoName: "widget",
		ItemType: db.WorkspaceItemTypeIssue, ItemNumber: 7,
		GitHeadRef: "kenn-forge/issue-7", WorkspaceBranch: "kenn-forge/issue-7",
		WorktreePath: issueWorktree, Status: "ready",
	}
	require.NoError(database.InsertWorkspace(t.Context(), issueWorkspace))
	issueRepo, err := database.GetRepoByIdentity(
		t.Context(), verifiedGitHubRepoIdentity("github.com", "acme", "widget"),
	)
	require.NoError(err)
	seedServerWorkspaceLaunchSpec(t, database, issueWorkspace, issueRepo.ID)

	kataWorktree := initServerWorkspaceGitRepo(t)
	require.NoError(database.InsertWorkspace(t.Context(), &db.Workspace{
		ID: "ws-kata-context", Platform: "github", PlatformHost: "github.com",
		RepoOwner: "acme", RepoName: "widget",
		ItemType: db.WorkspaceItemTypeKataTask,
		ItemKey: db.KataWorkspaceItemKey(db.WorkspaceKataMetadata{
			DaemonID: "home", ProjectUID: "project-1", IssueUID: "issue-kata-1",
		}),
		GitHeadRef: "kenn-forge/kata/task-123", WorkspaceBranch: "kenn-forge/kata/task-123",
		WorktreePath: kataWorktree, Status: "ready",
		KataMetadata: &db.WorkspaceKataMetadata{
			DaemonID: "home", ProjectUID: "project-1", ProjectName: "Widget",
			IssueUID: "issue-kata-1", ShortID: "KAT-12", Title: "Wire task context",
		},
	}))

	launch := func(workspaceID string) {
		t.Helper()
		req := httptest.NewRequest(
			http.MethodPost,
			"/api/v1/workspaces/"+workspaceID+"/runtime/sessions",
			bytes.NewBufferString(`{"target_key":"codex"}`),
		)
		req.Header.Set("Content-Type", "application/json")
		rec := httptest.NewRecorder()
		srv.ServeHTTP(rec, req)
		require.Equal(http.StatusOK, rec.Code, rec.Body.String())
	}

	launch("ws-issue-context")
	issueContext, err := os.ReadFile(filepath.Join(issueWorktree, "AGENTS.override.md"))
	require.NoError(err)
	assert.Contains(string(issueContext), "Source kind: provider issue")
	assert.Contains(string(issueContext), "Issue: #7")
	assert.NotContains(string(issueContext), "Test Issue")
	issueStatus := strings.TrimSpace(string(runServerWorkspaceTestGit(t, issueWorktree, "status", "--porcelain")))
	assert.Empty(issueStatus)

	// A pre-existing user-owned file makes launch succeed without touching
	// it: context delivery is silently skipped by design.
	userOwned := "# My own instructions\n"
	require.NoError(os.WriteFile(filepath.Join(kataWorktree, "AGENTS.override.md"), []byte(userOwned), 0o644))
	launch("ws-kata-context")
	preserved, err := os.ReadFile(filepath.Join(kataWorktree, "AGENTS.override.md"))
	require.NoError(err)
	require.Equal(userOwned, string(preserved))
	require.NoError(os.Remove(filepath.Join(kataWorktree, "AGENTS.override.md")))

	launch("ws-kata-context")
	kataContext, err := os.ReadFile(filepath.Join(kataWorktree, "AGENTS.override.md"))
	require.NoError(err)
	assert.Contains(string(kataContext), "Source kind: Kata task")
	assert.Contains(string(kataContext), "Kata daemon: home")
	assert.Contains(string(kataContext), "Issue UID: issue-kata-1")
	assert.Contains(string(kataContext), "Short ID: KAT-12")
	assert.Contains(string(kataContext), "<untrusted-source-text>Wire task context</untrusted-source-text>")
	kataStatus := strings.TrimSpace(string(runServerWorkspaceTestGit(t, kataWorktree, "status", "--porcelain")))
	assert.Empty(kataStatus)
}

